// 01_variables_and_mutability.rs
// 主题：变量与可变性
//
// Rust 默认变量是不可变的（immutable）。
// 如果需要修改变量的值，必须用 `mut` 关键字声明它为可变变量。
// 常量（const）在整个程序运行期间永远不可变，且必须标注类型。
// 遮蔽（shadowing）允许用同名变量重新绑定一个新值（甚至是不同类型）。

fn main() {
    // ---- 不可变变量 ----
    // 变量默认不可变，编译器会阻止对不可变变量的二次赋值
    let x = 5;
    println!("不可变变量 x = {}", x);

    // 下面这行会导致编译错误，因为 x 不可变：
    // x = 6;

    // ---- 可变变量 ----
    // 使用 mut 关键字声明可变变量
    let mut y = 5;
    println!("可变变量 y 初始值 = {}", y);
    y = 6; // 合法：y 是可变的
    println!("可变变量 y 修改后 = {}", y);

    // ---- 常量 ----
    // 常量使用 const 关键字，必须显式标注类型，且不能使用 mut
    // 常量可以在任意作用域（包括全局作用域）中声明
    const MAX_POINTS: u32 = 100_000; // 下划线可提高数字可读性
    println!("常量 MAX_POINTS = {}", MAX_POINTS);

    // ---- 遮蔽（Shadowing）----
    // 使用 let 重新声明同名变量，会遮蔽之前的变量
    // 与 mut 不同：遮蔽可以改变变量类型，且在遮蔽后变量仍是不可变的
    let z = 5;
    let z = z + 1; // 遮蔽：z 被重新绑定为 6
    {
        // 内部作用域中的遮蔽只在该作用域内有效
        let z = z * 2; // 内部 z = 12
        println!("内部作用域中，遮蔽后的 z = {}", z);
    }
    println!("外部作用域中的 z = {}", z); // z 仍是 6

    // 遮蔽还允许改变类型
    let spaces = "   "; // 字符串类型
    let spaces = spaces.len(); // 遮蔽为 usize 整数类型
    println!("spaces（字符数）= {}", spaces);

    // ---- 变量解构 ----
    // 可以通过模式匹配同时绑定多个变量
    let (a, b, c) = (1, 2, 3);
    println!("解构绑定：a={}, b={}, c={}", a, b, c);
}
